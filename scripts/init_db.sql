-- Business Glossary with Technical Mappings
CREATE OR REPLACE VIEW V_BUSINESS_GLOSSARY AS
SELECT
    bt.ID,
    bt.TERM,
    bt.SYNONYMS,
    bt.DEFINITION,
    bt.CATEGORY,
    bt.CONFIDENCE_SCORE,
    bt.VALIDATED_BY,
    bt.VALIDATED_AT,
    (
        SELECT JSON_ARRAYAGG(
            JSON_OBJECT(
                'technical_artifact_id' VALUE ta.ID,
                'artifact_type' VALUE ta.ARTIFACT_TYPE,
                'name' VALUE ta.NAME,
                'source_system' VALUE ta.SOURCE_SYSTEM,
                'path' VALUE ta.PATH,
                'mapping_type' VALUE btm.MAPPING_TYPE,
                'confidence_score' VALUE btm.CONFIDENCE_SCORE,
                'transformation_logic' VALUE btm.TRANSFORMATION_LOGIC,
                'business_rule' VALUE btm.BUSINESS_RULE
            )
        )
        FROM BUSINESS_TECHNICAL_MAPPINGS btm
        JOIN TECHNICAL_ARTIFACTS ta ON btm.TECHNICAL_ARTIFACT_ID = ta.ID
        WHERE btm.BUSINESS_TERM_ID = bt.ID
    ) AS TECHNICAL_MAPPINGS
FROM BUSINESS_TERMS bt;

-- Lineage View (Source -> Target)
CREATE OR REPLACE VIEW V_LINEAGE AS
SELECT
    t.ID AS TRANSFORMATION_ID,
    src.ARTIFACT_TYPE AS SOURCE_TYPE,
    src.NAME AS SOURCE_NAME,
    src.SOURCE_SYSTEM AS SOURCE_SYSTEM,
    src.PATH AS SOURCE_PATH,
    tgt.ARTIFACT_TYPE AS TARGET_TYPE,
    tgt.NAME AS TARGET_NAME,
    tgt.SOURCE_SYSTEM AS TARGET_SYSTEM,
    tgt.PATH AS TARGET_PATH,
    t.TRANSFORMATION_LOGIC,
    t.BUSINESS_RULE,
    t.SOURCE_SYSTEM AS TRANSFORMATION_SYSTEM
FROM TRANSFORMATIONS t
LEFT JOIN TECHNICAL_ARTIFACTS src ON t.SOURCE_ARTIFACT_ID = src.ID
LEFT JOIN TECHNICAL_ARTIFACTS tgt ON t.TARGET_ARTIFACT_ID = tgt.ID;

